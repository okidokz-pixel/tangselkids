/** Returns which area group a place belongs to. */
export function getAreaGroup(area: string): "bintaro" | "bsd" | "tangerang" | "all" {
  const a = area.toLowerCase();
  // Explicit "All" / "Semua" and legacy "Bintaro/BSD" both mean area-wide.
  if (a.includes("semua") || a.trim() === "all") return "all";
  if (a.includes("bintaro") && a.includes("bsd")) return "all";
  // Tangerang Selatan is the umbrella that contains Bintaro + BSD → area-wide.
  // Check this BEFORE the bare "tangerang" match below, since "tangerang selatan"
  // also contains the substring "tangerang".
  if (a.includes("tangsel") || a.includes("tangerang selatan")) return "all";
  if (a.includes("bsd")) return "bsd";
  if (a.includes("bintaro")) return "bintaro";
  // A bare "Tangerang" (Kota/Kabupaten Tangerang, north of Tangsel) is its own group.
  if (a.includes("tangerang")) return "tangerang";
  return "bintaro";
}

/**
 * Returns true if the place matches at least one of the selected area groups.
 * Pass an empty array (or ["all"]) to match everything.
 * Places whose getAreaGroup() === "all" always match any selection.
 */
export function placeMatchesAreas(place: Place, selectedAreas: string[]): boolean {
  if (selectedAreas.length === 0 || selectedAreas.includes("all")) return true;
  const group = getAreaGroup(place.area);
  // Area-wide places (legacy "Bintaro/BSD" / "All") cover Bintaro + BSD only,
  // NOT Tangerang — so the Tangerang filter shows only schools tagged Tangerang.
  if (group === "all") return selectedAreas.includes("bintaro") || selectedAreas.includes("bsd");
  return selectedAreas.includes(group);
}

/**
 * True if the place matches a free-text neighborhood/kecamatan query (e.g.
 * "Pamulang"). Used by the smart-search `loc` filter across every category.
 */
export function placeMatchesLoc(place: Place, loc: string): boolean {
  if (!loc) return true;
  const q = loc.toLowerCase();
  return (place.locationDetail ?? "").toLowerCase().includes(q)
    || (place.address ?? "").toLowerCase().includes(q)
    || place.name.toLowerCase().includes(q)
    || (place.area ?? "").toLowerCase().includes(q);
}

/**
 * Generic free-text "feature" match for smart search — the long tail of
 * extracurriculars (Karate), facilities (Mushola), course types (gimnastik),
 * methods (Montessori, Play-based), teaching language (Bilingual), etc. Every
 * requested feature must appear (normalized, punctuation/space-insensitive) in
 * some searchable text field. Scales to any keyword without enumeration.
 */
export function placeMatchesFeatures(place: Place, features: string[]): boolean {
  if (!features.length) return true;
  const norm = (x: string) => x.toLowerCase().replace(/[^a-z0-9]/g, "");
  const parts = [
    place.name, place.facilities, place.facilitiesEn, place.extracurriculars, place.extracurricularsEn,
    place.curriculum, place.curriculumCategory, place.description,
    place.teachingLanguageDisplay, place.teachingLanguage, place.daycareMethod, place.ageRange,
    (place.courseTypes ?? []).join(" "), (place.clinicServices ?? []).join(" "),
    (place.daycareAgeGroups ?? []).join(" "), (place.bahasa ?? []).join(" "),
    place.playgroundTypeRaw,
  ].filter((v): v is string => typeof v === "string" && v.length > 0);
  const hay = norm(parts.join(" "));
  return features.every((f) => {
    const fn = norm(f);
    return fn.length >= 3 && hay.includes(fn);
  });
}

export function formatPrice(price: number): string {
  if (price === 0) return "Gratis";
  if (price >= 1000000) {
    const val = price / 1000000;
    return val % 1 === 0 ? `${val}jt` : `${val.toFixed(1)}jt`;
  }
  return `${(price / 1000).toFixed(0)}k`;
}

export function formatPriceRange(min: number, max: number): string {
  if (min === 0 && max === 0) return "Gratis";
  return `Rp ${formatPrice(min)} – ${formatPrice(max)} / bln`;
}

export function formatTicketPrice(min: number, max: number): string {
  if (min === 0 && max === 0) return "Gratis";
  if (!max || max === min) return `Rp ${formatPrice(min)}`;
  return `Rp ${formatPrice(min)} – ${formatPrice(max)}`;
}

